-- A base column rename must preserve the exposed names and join keys of a stored query.
CREATE TABLE star_rename_base (id int PRIMARY KEY, "Old Key" int, qty int);
CREATE TABLE star_rename_peer ("Old Key" int PRIMARY KEY, label int);
INSERT INTO star_rename_base VALUES (1, 10, 7), (2, 20, 9), (3, NULL, 11);
