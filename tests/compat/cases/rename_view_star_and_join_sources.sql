CREATE VIEW star_rename_derived AS SELECT d.id, d."Old Key", d.qty FROM (SELECT * FROM star_rename_base) AS d;
CREATE VIEW star_rename_cte AS WITH stored AS (SELECT b.* FROM star_rename_base b) SELECT id, "Old Key", qty FROM stored;
CREATE VIEW star_rename_using AS SELECT * FROM star_rename_base LEFT JOIN star_rename_peer USING ("Old Key");
CREATE VIEW star_rename_natural AS SELECT * FROM star_rename_base NATURAL JOIN star_rename_peer;
CREATE VIEW star_rename_aliased AS SELECT s."Old Key", s.key_id, p.label FROM star_rename_base AS s(key_id) JOIN star_rename_peer p USING ("Old Key");
CREATE VIEW star_rename_qualified AS SELECT public.star_rename_base."Old Key", p.label FROM public.star_rename_base JOIN star_rename_peer p USING ("Old Key");
CREATE VIEW star_rename_transitive AS SELECT id, "Old Key", label FROM star_rename_using;
