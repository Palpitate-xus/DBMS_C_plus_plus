CREATE VIEW diff_jv_right AS SELECT id, increment_value AS step FROM diff_jv_map WHERE id >= 3;
CREATE VIEW diff_jv_joined AS SELECT v.id, v.total, m.increment_value + v.total AS final FROM diff_jv_left v JOIN diff_jv_map m ON v.id = m.id WHERE v.id > 0;
