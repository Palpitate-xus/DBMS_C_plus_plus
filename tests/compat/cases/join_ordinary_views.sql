SELECT v.id, r.id AS right_id, v.total, v.payload FROM diff_jv_left v LEFT JOIN diff_jv_map r ON v.id = r.id ORDER BY v.id;
SELECT r.id, v.payload, v.total FROM diff_jv_left v RIGHT JOIN diff_jv_map r ON v.id = r.id ORDER BY r.id;
SELECT coalesce(v.id, r.id) AS matched_id, v.total, r.increment_value FROM diff_jv_left v FULL JOIN diff_jv_map r ON v.id = r.id ORDER BY matched_id;
SELECT DISTINCT v.payload FROM diff_jv_left v CROSS JOIN diff_jv_map r ORDER BY v.payload;
SELECT v.*, w.step FROM diff_jv_left v JOIN diff_jv_right w USING (id) ORDER BY v.id;
SELECT * FROM diff_jv_left NATURAL FULL JOIN diff_jv_right ORDER BY id;
