CREATE VIEW diff_rv_calc AS SELECT id, quantity * 2 AS total FROM diff_rv_source WHERE quantity > 0;
CREATE VIEW diff_rv_chain AS SELECT c.total FROM diff_rv_calc AS c WHERE c.total > (SELECT s.quantity FROM diff_rv_source AS s WHERE s.id = 1);
CREATE VIEW diff_rv_direct AS SELECT public.diff_rv_source.quantity, id FROM public.diff_rv_source;
CREATE VIEW diff_rv_star AS SELECT * FROM diff_rv_source;
CREATE VIEW diff_rv_join AS SELECT s.id, quantity AS from_source, "Order Quantity" AS from_other FROM diff_rv_source AS s JOIN diff_rv_other AS o ON s.id = o.id WHERE "Order Quantity" > quantity;
CREATE VIEW diff_rv_derived AS SELECT d.quantity, d.id FROM (SELECT id, quantity FROM diff_rv_source) AS d;
CREATE VIEW diff_rv_scopes AS SELECT s.id, (SELECT s.quantity + o."Order Quantity" FROM diff_rv_other AS o WHERE o.id = s.id) AS total FROM diff_rv_source AS s;
CREATE SEQUENCE diff_rv_sequence;
CREATE VIEW diff_rv_volatile AS SELECT id, quantity, nextval('diff_rv_sequence') AS token FROM diff_rv_source;
