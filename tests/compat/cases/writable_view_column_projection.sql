CREATE SCHEMA write_shadow;
CREATE TABLE write_origin.orders (id int PRIMARY KEY, qty int DEFAULT 700, hidden int DEFAULT 800);
CREATE TABLE write_shadow.orders (id int PRIMARY KEY, qty int, hidden int);
