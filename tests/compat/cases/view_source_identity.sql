CREATE VIEW public.order_scalar_report AS SELECT (SELECT quantity FROM "Orders" WHERE id = 10) AS quantity;
CREATE VIEW public.order_set_report AS SELECT quantity FROM "Orders" UNION ALL SELECT quantity FROM view_west."Orders";
