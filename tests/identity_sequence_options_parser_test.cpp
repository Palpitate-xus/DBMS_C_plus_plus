#include "parser/parser.h"
#include <iostream>
#include <stdexcept>
#include <string>
#include <utility>
#include <vector>
using namespace dbms;
namespace {
unsigned checked = 0;
void need(bool good, const std::string& reason) {
    ++checked; if (!good) throw std::runtime_error(reason);
}
void options(const std::string& sql, bool alter,
             const std::vector<std::pair<std::string, std::string>>& wanted) {
    SQLParser parser; auto result = parser.parse(sql);
    need(result.success, "complete identity option syntax: " + sql);
    const ColumnDef* column = nullptr;
    if (alter) {
        const auto* stmt = dynamic_cast<const AlterTableStmt*>(result.stmt.get());
        need(stmt && stmt->subCommands.size() == 1, "one actual ALTER action");
        column = &stmt->subCommands.front().colDef;
    } else {
        const auto* stmt = dynamic_cast<const CreateTableStmt*>(result.stmt.get());
        need(stmt && stmt->columns.size() == 2, "both actual columns survive option list");
        column = &stmt->columns.front();
        need(stmt->columns.back().identityOptions.empty(), "options never leak to next column");
    }
    need(column->hasIdentityOptions, "explicit option-list presence");
    need(column->identityOptions == wanted, "actual ordered option identities and full values");
}
}
int main() {
    try {
        const std::string prefix = "CREATE TABLE identity_parser(id integer GENERATED ALWAYS AS IDENTITY (";
        options(prefix + "START WITH +10 INCREMENT BY -2 MINVALUE -40 MAXVALUE 20 CACHE 3 CYCLE),note text)", false,
            {{"start", "+10"}, {"increment", "-2"}, {"minvalue", "-40"}, {"maxvalue", "20"}, {"cache", "3"}, {"cycle", ""}});
        options(prefix + "NO MINVALUE NO MAXVALUE NO CYCLE),note text)", false,
            {{"nominvalue", ""}, {"nomaxvalue", ""}, {"nocycle", ""}});
        options(prefix + "SEQUENCE NAME \"A schema\".\"S.seq\" UNLOGGED OWNED BY NONE),note text)", false,
            {{"sequence_name", "\"A schema\".\"S.seq\""}, {"unlogged", ""}, {"ownedby", "NONE"}});
        options(prefix + "START 1 START 2 MINVALUE 1 NO MINVALUE LOGGED UNLOGGED),note text)", false,
            {{"start", "1"}, {"start", "2"}, {"minvalue", "1"}, {"nominvalue", ""}, {"logged", ""}, {"unlogged", ""}});
        options(prefix + "START 9223372036854775808 CACHE 1.0 RESTART WITH 5 AS bigint),note text)", false,
            {{"start", "9223372036854775808"}, {"cache", "1.0"}, {"restart", "5"}, {"as", "bigint"}});
        options("ALTER TABLE identity_parser ADD COLUMN id integer GENERATED BY DEFAULT AS IDENTITY(START 15 INCREMENT 3)", true,
            {{"start", "15"}, {"increment", "3"}});
        options("ALTER TABLE identity_parser ALTER COLUMN id ADD GENERATED ALWAYS AS IDENTITY(START 15 INCREMENT 3)", true,
            {{"start", "15"}, {"increment", "3"}});
        options("ALTER TABLE identity_parser ALTER COLUMN id SET GENERATED BY DEFAULT SET INCREMENT 7 RESTART WITH 40", true,
            {{"generated", "d"}, {"increment", "7"}, {"restart", "40"}});
        options("ALTER TABLE identity_parser ALTER COLUMN id SET START 20 RESTART", true,
            {{"start", "20"}, {"restart", ""}});
        options("ALTER TABLE identity_parser ALTER COLUMN id RESTART 30 SET NO MINVALUE SET NO MAXVALUE SET NO CYCLE", true,
            {{"restart", "30"}, {"nominvalue", ""}, {"nomaxvalue", ""}, {"nocycle", ""}});
        options("ALTER TABLE identity_parser ALTER COLUMN id SET INCREMENT 2 SET INCREMENT 3", true,
            {{"increment", "2"}, {"increment", "3"}});
        options("ALTER TABLE identity_parser ALTER COLUMN id SET GENERATED ALWAYS SET GENERATED BY DEFAULT", true,
            {{"generated", "a"}, {"generated", "d"}});
        for (const auto& body : {"SET", "SET AS bigint", "SET OWNED BY NONE", "SET RESTART 10",
                "RESTART WITH", "SET GENERATED ALWAYS nonsense", "SET INCREMENT 2 nonsense",
                "DROP IDENTITY nonsense", "ADD GENERATED ALWAYS AS IDENTITY(START 1) SET INCREMENT 2"}) {
            SQLParser parser;
            need(!parser.parse("ALTER TABLE identity_parser ALTER COLUMN id " + std::string(body)).success,
                 "invalid ALTER identity grammar consumes no ignored tail: " + std::string(body));
        }
        {
            SQLParser parser;
            auto parsed = parser.parse("ALTER TABLE identity_parser ALTER COLUMN id SET START 20, ALTER COLUMN id RESTART 30");
            const auto* stmt = parsed.success ? dynamic_cast<const AlterTableStmt*>(parsed.stmt.get()) : nullptr;
            need(stmt && stmt->subCommands.size() == 2, "comma separates actual identity alterations");
            need(stmt->subCommands[0].colDef.identityOptions ==
                 std::vector<std::pair<std::string,std::string>>{{"start","20"}}, "first ALTER clause owns its option");
            need(stmt->subCommands[1].colDef.identityOptions ==
                 std::vector<std::pair<std::string,std::string>>{{"restart","30"}}, "second ALTER clause owns its option");
        }
        for (const auto& body : {"", "START", "START WITH", "START 1, CACHE 3", "START 1 nonsense 2", "CACHE '2'", "SEQUENCE NAME public.", "\"start\" WITH 2", "START WITH -"}) {
            SQLParser parser;
            need(!parser.parse(prefix + body + "),note text)").success, "invalid identity option grammar: " + std::string(body));
        }
        std::cout << "[IDENTITY OPTIONS PARSER] checked=" << checked << " full_semantic_options=false\n";
        return 0;
    } catch (const std::exception& error) {
        std::cerr << "IDENTITY_PARSER_FAIL " << error.what() << '\n'; return 1;
    }
}
