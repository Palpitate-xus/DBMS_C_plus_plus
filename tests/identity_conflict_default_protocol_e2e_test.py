#!/usr/bin/env python3
"""Identity/default conflict values, allocation demand and genuine NULLs.

The expected values were checked against PostgreSQL 18.6. This exercises
ordinary simple-query DML; it does not test sequence session-current values.
"""
import importlib.util
import socket
import sys
import uuid
from pathlib import Path


def cases(table):
    result = []

    def add(name, sql, rows=None, oids=None, tag=None, state=None):
        result.append(dict(id=name, sql=sql, rows=rows, oids=oids, tag=tag, state=state))

    add('create', f"CREATE TABLE {table}(k integer PRIMARY KEY,id smallint GENERATED ALWAYS AS IDENTITY(START 10 INCREMENT 2),note text DEFAULT 'stored')")
    columns = [23, 21, 25]
    add('seed', f"INSERT INTO {table}(k,note) VALUES(1,'é中🙂') RETURNING k,id,note", [['1', '10', 'é中🙂']], columns, 'INSERT 0 1')
    add('no-conflict', f"INSERT INTO {table}(k,note) VALUES(2,NULL) ON CONFLICT(k) DO UPDATE SET id=DEFAULT,note=excluded.note RETURNING k,id,note", [['2', '12', None]], columns, 'INSERT 0 1')
    add('after-no-conflict', f"INSERT INTO {table}(k) VALUES(3) RETURNING k,id,note", [['3', '14', 'stored']], columns, 'INSERT 0 1')
    add('conflict', f"INSERT INTO {table}(k,note) VALUES(1,'changed') ON CONFLICT(k) DO UPDATE SET id=DEFAULT,note=excluded.note RETURNING k,id,note", [['1', '18', 'changed']], columns, 'INSERT 0 1')
    for condition in ['false', 'NULL']:
        add('where-' + condition, f"INSERT INTO {table}(k) VALUES(1) ON CONFLICT(k) DO UPDATE SET id=DEFAULT WHERE {condition} RETURNING k,id,note", [], columns, 'INSERT 0 0')
    add('after-where', f"INSERT INTO {table}(k) VALUES(4) RETURNING k,id,note", [['4', '24', 'stored']], columns, 'INSERT 0 1')
    for name, assignment, state in [
            ('explicit', 'id=999', '428C9'), ('explicit-null', 'id=NULL WHERE false', '428C9'),
            ('missing-function', 'id=missing_identity_conflict_function()', '42883'),
            ('missing-column', 'id=999 WHERE missing_identity_conflict_column=1', '42703')]:
        add(name, f"INSERT INTO {table}(k) VALUES(8) ON CONFLICT(k) DO UPDATE SET {assignment}", [], state=state)
    for index, assignment in enumerate(['id=DEFAULT+1', 'id=DEFAULT,', 'id=DEFAULT, WHERE false',
                                        'id=DEFAULT note=excluded.note', 'id=DEFAULT junk', 'id=DEFAULT WHERE',
                                        'id=DEFAULT,id=DEFAULT']):
        add('invalid-grammar-' + str(index), f"INSERT INTO {table}(k) VALUES(1) ON CONFLICT(k) DO UPDATE SET {assignment}", [], state='42601')
    add('after-analysis-errors', f"INSERT INTO {table}(k) VALUES(5) RETURNING k,id,note", [['5', '26', 'stored']], columns, 'INSERT 0 1')
    add('rename-sequence', f"ALTER SEQUENCE {table}_id_seq RENAME TO {table}_renamed_sequence")
    add('update-default', f"UPDATE {table} SET id=DEFAULT WHERE k=2 RETURNING k,id,note", [['2', '28', None]], columns, 'UPDATE 1')
    add('renamed-conflict', f"INSERT INTO {table}(k) VALUES(1) ON CONFLICT(k) DO UPDATE SET id=DEFAULT,note=DEFAULT RETURNING k,id,note", [['1', '32', 'stored']], columns, 'INSERT 0 1')
    add('snapshot', f"SELECT k,id,note FROM {table} ORDER BY k", [['1', '32', 'stored'], ['2', '28', None], ['3', '14', 'stored'], ['4', '24', 'stored'], ['5', '26', 'stored']], columns, 'SELECT 5')
    incoming = table + '_incoming'
    add('incoming-create', f"CREATE TABLE {incoming}(k integer PRIMARY KEY,id integer GENERATED BY DEFAULT AS IDENTITY(START 50 INCREMENT 5),note text,optional text,payload integer,g integer GENERATED ALWAYS AS(k*2) STORED)")
    columns = [23, 23, 25, 25, 23, 23]
    add('incoming-seed', f"INSERT INTO {incoming}(k) VALUES(1) RETURNING k,id,note,optional,payload,g", [['1', '50', None, None, None, '2']], columns, 'INSERT 0 1')
    add('incoming-copy', f"INSERT INTO {incoming}(k,note) VALUES(1,'é中🙂') ON CONFLICT(k) DO UPDATE SET id=excluded.id,note=excluded.note,optional=excluded.optional,payload=excluded.g RETURNING k,id,note,optional,payload,g", [['1', '55', 'é中🙂', None, '2', '2']], columns, 'INSERT 0 1')
    add('incoming-where', f"INSERT INTO {incoming}(k) VALUES(1) ON CONFLICT(k) DO UPDATE SET id=DEFAULT WHERE {incoming}.id=55 AND excluded.id=60 RETURNING k,id,note,optional,payload,g", [['1', '65', 'é中🙂', None, '2', '2']], columns, 'INSERT 0 1')
    add('incoming-false', f"INSERT INTO {incoming}(k) VALUES(1) ON CONFLICT(k) DO UPDATE SET id=DEFAULT WHERE excluded.id=0 RETURNING k,id,note,optional,payload,g", [], columns, 'INSERT 0 0')
    add('incoming-next', f"INSERT INTO {incoming}(k) VALUES(2) RETURNING k,id,note,optional,payload,g", [['2', '75', None, None, None, '4']], columns, 'INSERT 0 1')
    key = table + '_key'
    columns = [23, 23, 25]
    add('key-create', f"CREATE TABLE {key}(k integer DEFAULT 7 PRIMARY KEY,id integer GENERATED ALWAYS AS IDENTITY(START 100 INCREMENT 10),note text)")
    add('key-seed', f"INSERT INTO {key}(note) VALUES('seed') RETURNING k,id,note", [['7', '100', 'seed']], columns, 'INSERT 0 1')
    add('key-conflict', f"INSERT INTO {key}(note) VALUES('candidate') ON CONFLICT(k) DO UPDATE SET id=DEFAULT,note=excluded.note RETURNING k,id,note", [['7', '120', 'candidate']], columns, 'INSERT 0 1')
    add('key-nothing', f"INSERT INTO {key}(note) VALUES('ignored') ON CONFLICT(k) DO NOTHING RETURNING k,id,note", [], columns, 'INSERT 0 0')
    add('key-next', f"INSERT INTO {key}(k,note) VALUES(8,'after') RETURNING k,id,note", [['8', '140', 'after']], columns, 'INSERT 0 1')
    return result


def main():
    root = Path(__file__).resolve().parent.parent
    spec = importlib.util.spec_from_file_location('identity_conflict_runner', root / 'tests/compat/pg_diff_runner.py')
    runner = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(runner)
    client = runner.load_protocol_client()
    reference = sys.argv[1:] == ['--reference18']
    assert not sys.argv[1:] or reference
    server = None
    if reference:
        host, port, user, database, password = runner._reference_connection_settings()
        sock = socket.create_connection((host, port), timeout=runner.wire_timeout())
        client.startup_reference(sock, user, database, password=password)
        runner.verify_reference_version(client, sock)
    else:
        server = runner.start_ours(client)
        sock = server['sock']
    table = 'identity_conflict_' + uuid.uuid4().hex[:10]
    failures = []
    controls = cases(table)
    try:
        for item in controls:
            messages = client.simple_query(sock, item['sql'])
            actual = runner.decode_wire_result(messages, include_types=True)
            good = actual[1] == item['state'] and [body for kind, body in messages if kind == b'Z'] == [b'I']
            for expected, index in [('rows', 0), ('oids', 5), ('tag', 4)]:
                if item[expected] is not None:
                    good = good and actual[index] == item[expected]
            print('IDENTITY_CONFLICT_DEFAULT', item['id'], actual, 'PASS', good, flush=True)
            if not good:
                failures.append(dict(expected=item, actual=actual, wire=[(kind.hex(), body.hex()) for kind, body in messages]))
        print('IDENTITY_CONFLICT_DEFAULT_CHECKS', len(controls), 'FAILURES', failures, flush=True)
        assert not failures, failures
    finally:
        try:
            client.simple_query(sock, 'ROLLBACK')
            for name in [table, table + '_incoming', table + '_key']:
                client.simple_query(sock, f'DROP TABLE IF EXISTS {name}')
        finally:
            if server:
                runner.stop_ours(server)
                assert server['process'].returncode == 0, ('owned Main terminal', server['process'].returncode)
            else:
                sock.close()


if __name__ == '__main__':
    main()
